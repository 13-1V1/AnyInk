/**
	ANY-INK trace layer: what a drop or a paste on the edit canvas carries (Milestone 7,
	audit C8). Owner: SCAFFOLD (shared hooks; tracks do not edit this file).

	Pure helpers with no editor and no DOM globals, so they run in jsdom. The hook in
	src/edit_canvas/events_drag_drop_paste.js decides what to do with the answers:
	- a dropped SVG file keeps upstream's shape import;
	- a dropped or pasted image goes to importTraceImage (trace_import.js), and the
	  image test is passed in (isTraceImageFile) so track C owns the one definition;
	- pasted text no longer imports SVG code (C8); it gets PASTE_TEXT_HINT;
	- anything else dropped gets DROP_HINT.

	Ctrl+V arrives twice: the keydown handler in events_keyboard.js, then a real paste
	event carrying the clipboard (at the canvas when it has focus, else at the page body,
	where a document listener takes it). makePasteGate() lets the keydown wait a moment
	and read the async clipboard only when no paste event came, and drops the second
	delivery of one paste event (the canvas, its host element, and the document listen).
	A refused read is flagged (denied) so the paste can say so (CLIPBOARD_BLOCKED_HINT);
	clipboardReadState() tells, without a prompt, whether a read would ask the user.
*/

export const DROP_HINT =
	'Drop a PNG, JPEG, or WebP image to trace over it, or an SVG file to import its shapes.';

export const PASTE_TEXT_HINT =
	'To import SVG shapes, drop an .svg file on the canvas. Paste an image to trace over it.';

export const PASTE_FILE_HINT = 'Paste a PNG, JPEG, or WebP image to trace over it.';

export const NOT_TRACEABLE_HINT =
	'Open a character, ligature, or component to add a trace image to it.';

export const CLIPBOARD_BLOCKED_HINT =
	'ANY-INK is not allowed to read the clipboard. Allow Clipboard in the site settings, or drop the image on the canvas.';

/** How long a Ctrl+V keydown waits for the paste event before reading the clipboard. */
export const PASTE_EVENT_WAIT_MS = 100;

/**
 * @param {File | Blob | null | undefined} file
 * @returns {Boolean} true for an SVG file (by type or by name)
 */
export function isSVGFile(file) {
	if (!file) return false;
	const type = String(file.type || '')
		.split(';')[0]
		.trim()
		.toLowerCase();
	if (type === 'image/svg+xml') return true;
	return /\.svg$/i.test(String(file.name || ''));
}

/**
 * @param {Object | null | undefined} item - the item on the edit canvas
 * @returns {Boolean} true for a glyph, ligature, or component (they carry item.anyink)
 */
export function isTraceableItem(item) {
	return (
		!!item &&
		typeof item === 'object' &&
		item.objType !== 'KernGroup' &&
		!!item.anyink &&
		typeof item.anyink === 'object'
	);
}

/**
 * @param {File | null | undefined} file - first file of a drop
 * @param {Function} isImage - (file) => Boolean, normally isTraceImageFile
 * @returns {'svg' | 'image' | 'other'}
 */
export function classifyDroppedFile(file, isImage) {
	if (!file) return 'other';
	if (isSVGFile(file)) return 'svg';
	if (safeTest(isImage, file)) return 'image';
	return 'other';
}

/**
 * Reads a paste event's DataTransfer.
 * @param {DataTransfer | Object | null | undefined} data - event.clipboardData
 * @param {Function} isImage - (file) => Boolean, normally isTraceImageFile
 * @returns {{image: File | null, text: Boolean, files: Number}}
 *   image: the first traceable image (SVG never counts); text: plain or HTML text is
 *   present; files: how many files came along
 */
export function summarizePaste(data, isImage) {
	const out = { image: null, text: false, files: 0 };
	if (!data) return out;

	const files = [];
	for (const item of listOf(data.items)) {
		if (item?.kind !== 'file' || typeof item.getAsFile !== 'function') continue;
		const file = item.getAsFile();
		if (file) files.push(file);
	}
	if (!files.length) files.push(...listOf(data.files).filter(Boolean));
	out.files = files.length;
	out.image = files.find((file) => !isSVGFile(file) && safeTest(isImage, file)) || null;

	const types = listOf(data.types).map((type) => String(type).toLowerCase());
	out.text = types.some((type) => type === 'text' || type.startsWith('text/'));
	if (!out.text && typeof data.getData === 'function') {
		try {
			out.text = !!data.getData('text/plain');
		} catch {
			out.text = false;
		}
	}
	return out;
}

/**
 * Reads the async clipboard (navigator.clipboard.read) for a Ctrl+V that arrived with
 * no paste event. Never throws: a refused permission or a missing API reads as empty.
 * @param {Object | null | undefined} clipboard - navigator.clipboard
 * @param {Function} isImage - (blob) => Boolean; gets a Blob with a type and no name
 * @returns {Promise<{image: Blob | null, text: Boolean, denied: Boolean}>} denied: the
 *   browser refused the read (permission blocked, or its prompt dismissed)
 */
export async function readClipboardImage(clipboard, isImage) {
	const out = { image: null, text: false, denied: false };
	if (!clipboard || typeof clipboard.read !== 'function') return out;
	let items;
	try {
		items = await clipboard.read();
	} catch (error) {
		out.denied = error?.name === 'NotAllowedError' || error?.name === 'SecurityError';
		return out;
	}
	for (const item of listOf(items)) {
		for (const rawType of listOf(item?.types)) {
			const type = String(rawType).toLowerCase();
			if (type.startsWith('text/')) {
				out.text = true;
				continue;
			}
			if (!type.startsWith('image/') || type === 'image/svg+xml') continue;
			let blob;
			try {
				blob = await item.getType(rawType);
			} catch {
				continue;
			}
			if (!blob) continue;
			const typed = blob.type ? blob : new Blob([blob], { type });
			if (safeTest(isImage, typed)) {
				out.image = typed;
				return out;
			}
		}
	}
	return out;
}

/**
 * What Chrome says about reading the clipboard, without asking the user.
 * @param {Object | null | undefined} permissions - navigator.permissions
 * @returns {Promise<'granted' | 'prompt' | 'denied' | 'unknown'>} 'unknown' when the
 *   browser cannot tell (no API, or no 'clipboard-read' permission name). Never throws.
 */
export async function clipboardReadState(permissions) {
	if (!permissions || typeof permissions.query !== 'function') return 'unknown';
	try {
		const state = (await permissions.query({ name: 'clipboard-read' }))?.state;
		return state === 'granted' || state === 'prompt' || state === 'denied' ? state : 'unknown';
	} catch {
		return 'unknown';
	}
}

/**
 * One gate per page. See the header for why Ctrl+V needs one.
 * @param {Object} [options]
 * @param {Function} [options.now] - clock in ms (tests pass a fake)
 * @param {Function} [options.wait] - (fn, ms) => void, default setTimeout
 * @param {Number} [options.delayMS] - how long the keydown waits for a paste event
 * @returns {{firstSight: Function, notePasteEvent: Function, afterKeyboardPaste: Function}}
 */
export function makePasteGate({
	now = () => Date.now(),
	wait = (fn, ms) => setTimeout(fn, ms),
	delayMS = PASTE_EVENT_WAIT_MS,
} = {}) {
	const seen = new WeakSet();
	let lastPasteEvent = -Infinity;
	return {
		/**
		 * @param {Event} event
		 * @returns {Boolean} false when this same event object was already handled
		 */
		firstSight(event) {
			if (!event || typeof event !== 'object') return true;
			if (seen.has(event)) return false;
			seen.add(event);
			return true;
		},
		/** A real paste event arrived (it carries the clipboard). */
		notePasteEvent() {
			lastPasteEvent = now();
		},
		/**
		 * Runs fn after delayMS unless a paste event arrived since this call.
		 * @param {Function} fn
		 */
		afterKeyboardPaste(fn) {
			const pressedAt = now();
			wait(() => {
				if (lastPasteEvent >= pressedAt) return;
				fn();
			}, delayMS);
		},
	};
}

// --------------------------------------------------------------
// Helpers
// --------------------------------------------------------------

function listOf(value) {
	if (!value) return [];
	try {
		return Array.from(value);
	} catch {
		return [];
	}
}

function safeTest(test, value) {
	if (typeof test !== 'function') return false;
	try {
		return !!test(value);
	} catch {
		return false;
	}
}
